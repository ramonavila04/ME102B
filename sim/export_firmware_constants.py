#!/usr/bin/env python3
"""Write include/mechanism.h from the simulated mechanism, so the firmware moves the
motor exactly as the simulator did (index angle, speed, ramps, dwell, step limit).

    python sim/export_firmware_constants.py [variant]     # default v2_inclined_disc

One block per pill; pick it with a build flag, e.g. `-DMECH_PILL_SMALL`. Iron (the
team's test pill) is the default.
"""
from __future__ import annotations

import importlib
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sim.engine import JAM_SPEED_FRAC, JAM_TIME  # noqa: E402
from sim.pills import PILLS  # noqa: E402

HEADER = """// Generated by sim/export_firmware_constants.py from the {variant} simulation spec.
// Do not hand-edit: change the mechanism or pills, then rerun the script.
//
// Contract between the mechanism design (sim/) and the firmware. One dispense:
//   repeat up to MECH_MAX_INDEX_STEPS times:
//     move forward MECH_INDEX_DEG (one pocket pitch) with the ramped profile;
//     wait MECH_SETTLE_MS counting beam-break edges; if >= 1 pill seen -> stop.
//   exactly 1 pill = OK; 2+ = DOUBLE; 0 after all steps = MISS/EMPTY (refill);
//   stall during a move = JAM: reverse MECH_REVERSE_DEG, retry that move up to
//   MECH_MAX_RETRIES times, then FAULT. Load cell = secondary confirmation.
// Firmware references only these names. Angles are output-shaft degrees.
// Select the pill/disc with one build flag: {flags} (default: iron).
#pragma once
#include <stdint.h>
"""


def block(name: str, d: dict, pill_id: str, first: bool, flag: str) -> str:
    move_s = (math.radians(d["index_deg"]) / (d["rpm"] * 2 * math.pi / 60)) + d["accel_s"]
    drop_ms = int(math.ceil((move_s + d["settle_s"]) * 1000 / 100.0) * 100 + 200)
    mass_min = round(0.8 * PILLS[pill_id].mass_g, 3)
    cond = f"#{'if' if first else 'elif'} defined({flag})" if flag else "#else"
    return f"""{cond}
// {PILLS[pill_id].label}
constexpr const char* MECH_NAME = "{name} / {pill_id}";
constexpr float MECH_INDEX_DEG = {d['index_deg']:.1f}f;          // one notch pitch
constexpr float MECH_TARGET_RPM = {d['rpm']:.1f}f;               // output rpm while indexing (sim value)
constexpr uint32_t MECH_ACCEL_MS = {int(round(d['accel_s'] * 1000))};             // ramp up / ramp down (sim value)
constexpr uint32_t MECH_SETTLE_MS = {int(round(d['settle_s'] * 1000))};            // dwell per step; pill slides the 50 mm duct
constexpr uint32_t MECH_DROP_WINDOW_MS = {drop_ms};       // move + settle + margin
constexpr uint32_t MECH_JAM_STALL_MS = {int(JAM_TIME * 1000)};         // matches sim JAM_TIME
constexpr float MECH_JAM_MIN_SPEED_FRAC = {JAM_SPEED_FRAC:.2f}f;  // matches sim JAM_SPEED_FRAC
constexpr float MECH_REVERSE_DEG = {d['index_deg'] / 2:.1f}f;         // back off half a pitch
constexpr uint8_t MECH_MAX_RETRIES = 2;
constexpr float MECH_HOME_OFFSET_DEG = 0.0f;      // set during BUILD.md step "home offset"
constexpr int MECH_MAX_INDEX_STEPS = {d['max_steps']};           // two revolutions (sim value)
constexpr float MECH_PILL_MASS_G_MIN = {mass_min}f;     // 80 % of nominal pill mass
"""


def main(variant: str = "v2_inclined_disc") -> str:
    mod = importlib.import_module(f"sim.variants.{variant}")
    order = ["small", "caplet", "cap0", "iron"]          # iron last = default (#else)
    flags = [f"MECH_PILL_{p.upper()}" for p in order[:-1]]
    out = HEADER.format(variant=variant, flags=", ".join(flags))
    for i, pid in enumerate(order):
        sp = mod.spec(pid)
        out += block(sp["name"], sp["drive"], pid, i == 0, flags[i] if i < len(flags) else "")
    out += "#endif\n"
    path = ROOT / "include" / "mechanism.h"
    path.write_text(out)
    return str(path)


if __name__ == "__main__":
    print("wrote", main(*sys.argv[1:]))
