#!/usr/bin/env python3
"""Collect results/<variant>/<pill>.json into results/COMPARISON.md and viewer/summary.json.

    python -m sim.summarize
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {
    "v0_original": "V0 original (team CAD)",
    "v1_fixed_rotor": "V1 fixed rotor (minimal fix)",
    "v2_inclined_disc": "V2 inclined pocket disc",
    "v2_inclined_disc_recheck": "V2 inclined pocket disc (re-check, final test setup)",
    "v3_shuttle": "V3 reciprocating shuttle",
}
PILL_ORDER = ["iron", "small"]
FAIL_KEYS = ["jam", "double", "miss", "lost", "leak", "empty"]


def collect():
    rows = []
    for vdir in sorted((ROOT / "results").iterdir()):
        if not vdir.is_dir() or vdir.name not in NAMES:
            continue
        for pill in PILL_ORDER:
            f = vdir / f"{pill}.json"
            if not f.exists():
                continue
            s = json.loads(f.read_text())["summary"]
            rows.append(dict(variant=NAMES[vdir.name], variant_id=vdir.name, pill=pill, **s))
    return rows


def main():
    rows = collect()
    (ROOT / "viewer").mkdir(exist_ok=True)
    (ROOT / "viewer" / "summary.json").write_text(json.dumps(dict(rows=rows), indent=1))
    lines = ["# Simulated dispense results", "",
             "Generated by `python -m sim.summarize` from `results/<variant>/<pill>.json`.",
             "Each trial: random fill, pill sizes within tolerance, friction 0.2–0.6, random",
             "start pose, then 3 dispense commands. Counts are per dispense cycle. A trial stops",
             "at its first jam, so a jamming design completes fewer than 3 cycles per trial.",
             "A row passes only with zero failures of every kind.", "",
             "Only iron and small tablets are reported: the caplet and size-0 capsule kits have",
             "not passed and are experimental (see `cad/variants/v2_inclined_disc/DESIGN.md`).",
             "The V2 campaign rows were run before a fix to the test's pill-placement check; the",
             "re-check rows repeat 50 trials per pill on the final test setup, same geometry.", "",
             "| Variant | Pill | Trials | Cycles | OK | Jam | Double | Miss | Lost | Leak | Empty | Trials with a jam | Unstable / anomaly trials | Verdict |",
             "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for r in rows:
        o = r["outcomes"]
        fail = sum(o.get(k, 0) for k in FAIL_KEYS) + r.get("errors", 0) + r.get("unstable_trials", 0)
        lines.append(f"| {r['variant']} | {r['pill']} | {r['trials']} | {r['cycles']} | {o.get('ok', 0)} | "
                     + " | ".join(str(o.get(k, 0)) for k in FAIL_KEYS)
                     + f" | {100 * r['jam_rate_per_trial']:.1f} % | {r.get('unstable_trials', 0)} / {r.get('anomaly_trials', 0)} | "
                     + ("**pass**" if fail == 0 else "fail") + " |")
    lines += ["", "## Jam sites", ""]
    for r in rows:
        if r["jam_sites"]:
            sites = "; ".join(f"{k}: {v}" for k, v in sorted(r["jam_sites"].items(), key=lambda kv: -kv[1]))
            lines.append(f"- **{r['variant']} / {r['pill']}**: {sites}")
    (ROOT / "results" / "COMPARISON.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
